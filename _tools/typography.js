'use strict';
// Типографика текста статей: чистит мусор вёрстки Битрикса и приводит
// пунктуацию к русским правилам. Работает только с текстом между тегами,
// атрибуты и разметку не трогает.

const SHORT_WORDS = ['в', 'во', 'на', 'за', 'по', 'из', 'от', 'до', 'к', 'ко', 'с', 'со',
  'у', 'о', 'об', 'обо', 'и', 'а', 'но', 'да', 'не', 'ни', 'для', 'при', 'под', 'над',
  'про', 'без', 'через', 'что', 'как', 'же', 'бы', 'ли'];

const UNITS = ['м', 'см', 'мм', 'км', 'кг', 'г', 'мин', 'ч', 'л', 'мл', '%', '₽', 'руб',
  'м²', 'кв', 'лет', 'год', 'года', 'м2'];

/* ---------- пунктуация в одном текстовом фрагменте ---------- */
function fixText(s) {
  if (!s) return s;

  // неразрывные пробелы Битрикса приводим к обычным, расставим свои осознанно
  s = s.replace(/ /g, ' ').replace(/&nbsp;/gi, ' ');

  // невидимый мусор и повторы пробелов
  s = s.replace(/[​‎‏﻿]/g, '');
  s = s.replace(/[ \t]{2,}/g, ' ');

  // пробел перед знаками препинания не нужен, после — нужен.
  // HTML-сущности (&gt; &nbsp; &amp;) не трогаем: точка с запятой в них — часть кода.
  s = s.replace(/(?<!&[a-z]{2,8})\s+([,.;:!?])/gi, '$1');
  s = s.replace(/(?<!&[a-z]{2,8})([,;:])(?=[^\s\d)»"])/gi, '$1 ');

  // повторяющиеся восклицания и вопросы
  s = s.replace(/!{2,}/g, '!').replace(/\?{2,}/g, '?').replace(/(\?!|!\?)+/g, '?!');
  // многоточие одним знаком
  s = s.replace(/\.{3,}/g, '…').replace(/…\.+/g, '…');

  // Кавычки-ёлочки по контексту, а не парами: в текстах встречаются
  // непарные кавычки, и парный поиск сдвигает всю последовательность.
  s = s.replace(/(^|[\s(\[{«„\-—])"/gm, '$1«');   // после пробела или скобки — открывающая
  s = s.replace(/"(?=[\s.,;:!?)\]}»“\-—]|$)/gm, '»'); // перед пробелом или знаком — закрывающая
  s = s.replace(/"/g, '»');                        // одиночные остатки
  // осечки предыдущих проходов: »Текст" и «Текст«
  s = s.replace(/(^|[\s(\[{])»(?=[^\s.,;:!?»])/gm, '$1«');
  // одиночные машинописные кавычки вокруг слов
  s = s.replace(/(^|[\s(])'([^']+)'(?=[\s).,;:!?]|$)/g, '$1«$2»');
  // вложенные одинаковые ёлочки -> лапки
  s = s.replace(/«([^«»]*)«([^«»]+)»([^«»]*)»/g, '«$1„$2“$3»');

  // дефис между пробелами — это тире
  s = s.replace(/(\s)-(\s)/g, '$1—$2');
  // Дефис в начале строки или абзаца — маркер списка или реплика, читается
  // как тире.  — метка выведенного тега, то есть граница блока.
  s = s.replace(/^[ \t]*-[ \t]+/gm, '— ');
  s = s.replace(/([\r\n])[ \t]*-[ \t]+/g, '$1— ');
  // диапазоны чисел через короткое тире без пробелов
  s = s.replace(/(\d)\s*[-—]\s*(\d)/g, '$1–$2');
  // «1- серебро» — дефис прилип к числу вместо пробела
  s = s.replace(/(\d)-\s+(?=[А-Яа-яЁёA-Za-z])/g, '$1 ');

  return s;
}

/* ---------- неразрывные пробелы (после fixText) ---------- */
function bindSpaces(s) {
  if (!s) return s;
  // короткие слова тянут за собой следующее
  const re = new RegExp('(^|[\\s(«„])(' + SHORT_WORDS.join('|') + ')\\s+', 'gi');
  s = s.replace(re, (m, pre, w) => pre + w + ' ');
  // число и единица измерения не разрываются
  const reUnit = new RegExp('(\\d)\\s+(' + UNITS.join('|') + ')(?=[\\s.,;:!?)]|$)', 'gi');
  s = s.replace(reUnit, '$1 $2');
  // инициалы и сокращения
  s = s.replace(/([А-ЯЁ]\.)\s*([А-ЯЁ]\.)\s*/g, '$1 $2 ');
  s = s.replace(/\bг\.\s+/g, 'г. ');
  s = s.replace(/\bул\.\s+/g, 'ул. ');
  s = s.replace(/(\d)\s+(₽|руб)/g, '$1 $2');
  return s;
}

/* ---------- обход html ----------
   Теги временно выносим за скобки и обрабатываем текст целиком: иначе
   фраза, разорванная <b> или ссылкой, не видна правилам как одно целое
   («тренер "Олимпии"» с кавычками по разные стороны тега).            */
const PH = '';
function processText(html, fn) {
  const tags = [];
  const masked = html.replace(/<[^>]+>/g, (t) => {
    tags.push(t);
    return PH + (tags.length - 1) + PH;
  });
  const done = fn(masked);
  return done.replace(new RegExp(PH + '(\\d+)' + PH, 'g'), (m, i) => tags[Number(i)]);
}

/* ---------- структурная чистка разметки ---------- */
function cleanMarkup(html) {
  let s = html;

  // служебные атрибуты и инлайновые стили из ворда
  s = s.replace(/\s(?:style|class|lang|dir|align|width|height|bgcolor|face)="[^"]*"/gi,
    (m) => /class="(?:article|table-wrap)/i.test(m) ? m : '');
  s = s.replace(/<\/?(?:font|o:p|st1:[a-z]+)\b[^>]*>/gi, '');
  s = s.replace(/<span\b[^>]*>/gi, '').replace(/<\/span>/gi, '');

  // Word дробит фразу на куски: <b>-</b> <b>17</b><b> мая</b>.
  // Склеиваем соседние одинаковые обёртки, иначе правила видят обрывки,
  // а не предложение (и текст выглядит рвано).
  // Якоря старого формата <a name="..."> — это точки перехода, а не ссылки:
  // переводим в современный id, иначе они выглядят как ссылки в никуда.
  s = s.replace(/<a\s+name="([^"]+)"[^>]*>\s*<\/a>/gi, '<span id="$1"></span>');
  // ссылка, внутри которой только пробелы, — невидимая цель для клика
  s = s.replace(/<a\b[^>]*>([\s\S]*?)<\/a>/gi, (m0, inner) => {
    if (/<img|<svg/i.test(inner)) return m0;
    const text = inner.replace(/<[^>]+>/g, '').replace(/&nbsp;/gi, ' ').trim();
    return text ? m0 : inner;
  });
  s = s.replace(/<a\b[^>]*href="https?:\/\/"[^>]*>([\s\S]*?)<\/a>/gi, '$1');
  // <a> без адреса — остаток крошек Битрикса, разворачиваем в текст
  s = s.replace(/<a(?![^>]*\bhref=)[^>]*>([\s\S]*?)<\/a>/gi, '$1');

  // сперва разворачиваем обёртку вокруг одного знака: она мешает склейке
  s = s.replace(/<(b|strong|em|i|u)>\s*([-–—•*])\s*<\/\1>/gi, '$2 ');
  for (let i = 0; i < 6; i++) {
    const before = s;
    s = s.replace(/<(b|strong|em|i|u)>([\s\S]*?)<\/\1>(\s*)<\1>/gi, '<$1>$2$3');
    if (s === before) break;
  }

  // Сначала убираем переносы МЕЖДУ блоками: они ничего не разделяют,
  // а если превратить их в границу абзаца — получится битая вложенность.
  s = s.replace(/(<\/(?:p|h[2-6]|ul|ol|div|table)>)\s*(?:<br\s*\/?>\s*)+/gi, '$1');
  s = s.replace(/(?:<br\s*\/?>\s*)+(<(?:p|h[2-6]|ul|ol|div|table)\b)/gi, '$1');

  // и только потом серии переносов внутри абзаца делаем границами абзацев
  s = s.replace(/(?:<br\s*\/?>\s*){2,}/gi, '</p><p>');
  // одиночный перенос в конце абзаца не нужен
  s = s.replace(/(?:<br\s*\/?>\s*)+(<\/p>)/gi, '$1');
  s = s.replace(/(<p[^>]*>)(?:\s*<br\s*\/?>)+/gi, '$1');

  // пустые абзацы, заголовки и списки
  for (let i = 0; i < 3; i++) {
    s = s.replace(/<(p|h[2-6]|li|div)>\s*(?:&nbsp;| |<br\s*\/?>|\s)*<\/\1>/gi, '');
  }
  // абзац, состоящий только из картинки, разворачиваем
  s = s.replace(/<p>\s*(<img\b[^>]*>)\s*<\/p>/gi, '$1');

  // заголовки-крики приводим к нормальному виду
  s = s.replace(/<(h[2-6])([^>]*)>([\s\S]*?)<\/\1>/gi, (m, tag, attrs, inner) => {
    const plain = inner.replace(/<[^>]+>/g, '').trim();
    // ЗАГОЛОВОК ЦЕЛИКОМ КАПСОМ читается тяжело
    if (plain.length > 8 && plain === plain.toUpperCase() && /[А-ЯЁ]/.test(plain)) {
      const fixed = plain.charAt(0) + plain.slice(1).toLowerCase();
      return '<' + tag + attrs + '>' + fixed + '</' + tag + '>';
    }
    return m;
  });

  // «Уважаемые клиенты!» отдельной строкой — шум перед сутью.
  // Обращение бывает с уточнением («…клиенты Спорткомплекса «Олимпия»»),
  // обёрнуто в <b>/<strong> и завершено переносом вместо закрытия абзаца.
  s = s.replace(
    /<(p|h[2-6]|div)\b[^>]*>\s*(?:<(?:b|strong|em|i|u)\b[^>]*>\s*)*Уважаемые\s+(?:клиенты|посетители|родители|гости)[^<!?]{0,70}?[!.,;]?\s*(?:<\/(?:b|strong|em|i|u)>\s*)*(?:<br\s*\/?>\s*)*<\/\1>/gi,
    '');
  // обращение как отдельная строка, закрытая переносом или сразу новым блоком
  s = s.replace(
    /(?:<(?:b|strong|em|i|u)\b[^>]*>\s*)*Уважаемые\s+(?:клиенты|посетители|родители|гости)[^<!?]{0,70}?[!.,;]?\s*(?:<\/(?:b|strong|em|i|u)>\s*)*(?:<br\s*\/?>\s*|(?=<(?:p|h[2-6]|ul|ol|div)\b))/gi,
    '');
  // то же обращение в начале содержательного абзаца — убираем только его,
  // оставшееся предложение поднимаем с заглавной буквы
  s = s.replace(
    /(<(?:p|div)\b[^>]*>\s*)(?:<(?:b|strong|em|i|u)\b[^>]*>\s*)*Уважаемые\s+(?:клиенты|посетители|родители|гости)\s*[!.,;]\s*(?:<\/(?:b|strong|em|i|u)>\s*)*(?:<br\s*\/?>\s*)*([а-яёa-z])/gi,
    (m, pre, ch) => pre + ch.toUpperCase());

  s = listsFromMarkers(s);

  s = s.replace(/\n{3,}/g, '\n\n');
  return s.trim();
}

/* ---------- псевдосписки в настоящие ----------
   Новости о соревнованиях свёрстаны строками через <br> с маркером «•»,
   а достижения идут отдельными строками. Читается как сплошная лента,
   поэтому собираем каждого участника в один пункт списка.            */
function listsFromMarkers(html) {
  // Битрикс выдаёт и такое: <ul> без единого <li>, строки разделены <br>.
  // Разбираем его тем же правилом, что и абзац.
  return html.replace(/<(p|ul|ol)\b[^>]*>([\s\S]*?)<\/\1>/gi, (whole, tag, inner) => {
    if (tag !== 'p' && /<li\b/i.test(inner)) return whole;   // нормальный список не трогаем
    // Маркер может стоять не с начала строки: перед ним бывает текст
    // или закрытый абзац. Ставим границу строки перед каждым маркером.
    const normalized = inner
      .replace(/(<\/(?:p|div|h[1-6])>)\s*(?=[•·‣▪])/gi, '$1<br>')
      .replace(/([^>\s])\s+(?=[•·‣▪]\s)/g, '$1<br>');
    const lines = normalized.split(/<br\s*\/?>/i).map(x => x.trim()).filter(Boolean);
    const marked = lines.filter(l => /^\s*(?:<[^>]+>\s*)*[•·‣▪–—-]\s+/.test(l));
    if (marked.length < 2) return whole;      // не перечень

    const items = [];
    let lead = [];
    for (const line of lines) {
      if (/^\s*(?:<[^>]+>\s*)*[•·‣▪–—-]\s+/.test(line)) {
        items.push([line.replace(/^\s*((?:<[^>]+>\s*)*)[•·‣▪–—-]\s+/, '$1')]);
      } else if (items.length) {
        items[items.length - 1].push(line);   // продолжение пункта
      } else {
        lead.push(line);                      // текст до списка
      }
    }
    if (!items.length) return whole;

    const li = items.map(parts => {
      const head = parts[0];
      // хвост пункта — перечисление наград, собираем в одну строку
      const tail = parts.slice(1)
        .map(t => t.replace(/[;.]\s*$/, '').trim())
        .filter(Boolean);
      return '<li>' + head + (tail.length
        ? ' <span class="li-note">' + tail.join(', ') + '</span>'
        : '') + '</li>';
    }).join('');

    // Вводная часть бывает смесью готовых абзацев и голого текста.
    // Готовые блоки оставляем как есть, свободный текст оборачиваем сами,
    // иначе он выпадает из ритма отступов.
    const leadHtml = lead.map(chunk => {
      const t = chunk.trim();
      if (!t) return '';
      if (/^<(?:p|div|h[1-6]|ul|ol|table|figure)\b/i.test(t)) return t;
      // текст, за которым следует готовый блок
      const cut = t.search(/<(?:p|div|h[1-6]|ul|ol|table|figure)\b/i);
      if (cut > 0) {
        const head = t.slice(0, cut).trim();
        return (head ? '<p>' + head + '</p>' : '') + t.slice(cut);
      }
      return '<p>' + t + '</p>';
    }).join('');
    return leadHtml + '<ul class="post-list">' + li + '</ul>';
  });
}

/* ---------- публичная функция ---------- */
function polish(html) {
  let s = cleanMarkup(html);
  s = processText(s, fixText);
  s = processText(s, bindSpaces);
  // после чистки могли появиться пустые абзацы
  s = s.replace(/<(p|h[2-6])>\s*<\/\1>/gi, '');
  return s;
}

module.exports = { polish, fixText, bindSpaces, cleanMarkup };
